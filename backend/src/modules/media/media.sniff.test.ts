import { describe, expect, it } from 'vitest';
import { matchesSignature } from './media.sniff.js';

const bytes = (...values: number[]) => new Uint8Array(values);

/** Each stored type with a sample that carries its signature and one that does not. */
const SAMPLES: { type: string; good: Uint8Array; bad: Uint8Array }[] = [
  {
    type: 'image/webp',
    good: bytes(0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50),
    bad: bytes(0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x41, 0x56, 0x45),
  },
  {
    type: 'image/jpeg',
    good: bytes(0xff, 0xd8, 0xff, 0xe0),
    bad: bytes(0x89, 0x50, 0x4e, 0x47),
  },
  {
    type: 'audio/mpeg',
    good: bytes(0x49, 0x44, 0x33, 0x04),
    bad: bytes(0x4f, 0x67, 0x67, 0x53),
  },
  {
    type: 'audio/aac',
    good: bytes(0xff, 0xf1, 0x50, 0x80),
    bad: bytes(0xff, 0xfb, 0x90, 0x64),
  },
  {
    type: 'audio/mp4',
    good: bytes(0x00, 0x00, 0x00, 0x20, 0x66, 0x74, 0x79, 0x70, 0x4d, 0x34, 0x41, 0x20),
    bad: bytes(0x00, 0x00, 0x00, 0x20, 0x6d, 0x6f, 0x6f, 0x76),
  },
  {
    type: 'video/mp4',
    good: bytes(0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d),
    bad: bytes(0x1a, 0x45, 0xdf, 0xa3, 0x00, 0x00, 0x00, 0x00),
  },
  {
    type: 'audio/ogg',
    good: bytes(0x4f, 0x67, 0x67, 0x53, 0x00, 0x02),
    bad: bytes(0x66, 0x4c, 0x61, 0x43),
  },
  {
    type: 'video/webm',
    good: bytes(0x1a, 0x45, 0xdf, 0xa3, 0x9f, 0x42),
    bad: bytes(0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70),
  },
  {
    type: 'application/pdf',
    good: bytes(0x25, 0x50, 0x44, 0x46, 0x2d, 0x31, 0x2e, 0x37),
    bad: bytes(0x3c, 0x68, 0x74, 0x6d, 0x6c, 0x3e),
  },
];

describe('file signatures', () => {
  for (const { type, good, bad } of SAMPLES) {
    it(`recognises ${type} and refuses something else`, () => {
      expect(matchesSignature(type, good)).toBe(true);
      expect(matchesSignature(type, bad)).toBe(false);
    });
  }

  it('accepts an MP3 frame header with no ID3 tag', () => {
    expect(matchesSignature('audio/mpeg', bytes(0xff, 0xfb, 0x90, 0x64))).toBe(true);
    expect(matchesSignature('audio/mpeg', bytes(0xff, 0x1b))).toBe(false);
  });

  it('refuses a sample shorter than the signature', () => {
    expect(matchesSignature('application/pdf', bytes(0x25, 0x50, 0x44))).toBe(false);
    expect(matchesSignature('image/webp', bytes(0x52, 0x49, 0x46, 0x46, 0x00, 0x00, 0x00, 0x00, 0x57))).toBe(false);
    expect(matchesSignature('video/mp4', bytes(0x00, 0x00, 0x00, 0x18, 0x66, 0x74))).toBe(false);
    expect(matchesSignature('audio/mpeg', bytes(0xff))).toBe(false);
  });

  it('refuses a type it does not know', () => {
    expect(matchesSignature('image/svg+xml', bytes(0x3c, 0x73, 0x76, 0x67))).toBe(false);
  });
});
